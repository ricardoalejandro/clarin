// @vitest-environment node
import { describe, expect, it } from 'vitest'
import * as pki from 'pkijs'
import { createCertificateRequest, exportVaultKey, fromPem, generateVaultKey, importVaultFile, parseKeyMaterial, signJwt, verifyJwt } from './pkiOperations'

describe('personal key and certificate interoperability', () => {
  it('round trips AES JWK without exposing it as public data', async () => {
    const created = await generateVaultKey('aes', 256)
    expect(created.public_data).toBe('')
    const material = parseKeyMaterial(created.material)
    const exported = await exportVaultKey(material, 'jwk', '')
    const imported = await importVaultFile(new TextEncoder().encode(exported.data as string).buffer, 'key.jwk')
    expect(parseKeyMaterial(imported.material).secret).toBe(material.secret)
    expect(imported.bits).toBe(256)
    const protectedFile = await exportVaultKey(material, 'jwk-protected', 'synthetic-password')
    expect(protectedFile.data).not.toContain(material.secret)
    const reopened = await importVaultFile(new TextEncoder().encode(protectedFile.data as string).buffer, protectedFile.filename, 'synthetic-password')
    expect(parseKeyMaterial(reopened.material).secret).toBe(material.secret)
    await expect(importVaultFile(new TextEncoder().encode(protectedFile.data as string).buffer, protectedFile.filename, 'incorrect')).rejects.toThrow('autenticar')
    await expect(generateVaultKey('aes', 192)).rejects.toThrow('AES-128 o AES-256')
  })
  it.each(['P-256', 'P-384'])('signs and verifies JWT and rejects a different key or tampered token on %s', async curve => {
    const first = parseKeyMaterial((await generateVaultKey('ec', curve)).material)
    const second = parseKeyMaterial((await generateVaultKey('ec', curve)).material)
    const token = await signJwt(first, '{"sub":"synthetic-user","exp":4102444800}')
    expect(JSON.parse(await verifyJwt(first, token)).firma).toBe('verificada')
    await expect(verifyJwt(second, token)).rejects.toThrow('no son válidas')
    const parts = token.split('.'); parts[1] = parts[1].slice(0, -1) + (parts[1].endsWith('A') ? 'B' : 'A')
    await expect(verifyJwt(first, parts.join('.'))).rejects.toThrow('no son válidas')
    await expect(signJwt(first, '[]')).rejects.toThrow('objeto JSON')
    await expect(verifyJwt(first, await signJwt(first, '{"exp":1}'))).rejects.toThrow('fechas')
  })
  it('creates verifiable PKCS10 CSR and self-signed non-CA X509 with SAN', async () => {
    const key = parseKeyMaterial((await generateVaultKey('ec', 'P-256')).material)
    const request = await createCertificateRequest(key, 'test.example.invalid', ['test.example.invalid'])
    expect(await pki.CertificationRequest.fromBER(fromPem(request, 'CERTIFICATE REQUEST')).verify()).toBe(true)
    const pem = await createCertificateRequest(key, 'test.example.invalid', ['test.example.invalid'], true)
    const certificate = pki.Certificate.fromBER(fromPem(pem, 'CERTIFICATE'))
    expect(await certificate.verify(certificate)).toBe(true)
    expect(certificate.extensions?.find(item => item.extnID === '2.5.29.19')?.parsedValue).toMatchObject({ cA: false })
    const imported = await importVaultFile(new TextEncoder().encode(pem).buffer, 'certificate.pem')
    expect(imported.metadata.san).toEqual(['test.example.invalid'])
    expect(imported.metadata.subject).toContain('test.example.invalid')
    await expect(createCertificateRequest(key, 'example', ['http://invalid'])).rejects.toThrow('DNS válidos')
  })
  it('round trips protected PKCS8 and P12 and rejects wrong passwords', async () => {
    const key = parseKeyMaterial((await generateVaultKey('ec', 'P-256')).material)
    key.certificates = [await createCertificateRequest(key, 'test.example.invalid', [], true)]
    const encrypted = await exportVaultKey(key, 'pem', 'synthetic-password')
    expect(encrypted.data).toContain('ENCRYPTED PRIVATE KEY')
    const imported = await importVaultFile(new TextEncoder().encode(encrypted.data as string).buffer, encrypted.filename, 'synthetic-password')
    expect(parseKeyMaterial(imported.material).privateKey).toBe(key.privateKey)
    await expect(importVaultFile(new TextEncoder().encode(encrypted.data as string).buffer, encrypted.filename, 'incorrect')).rejects.toThrow('contraseña')
    const p12 = await exportVaultKey(key, 'p12', 'synthetic-password')
    const reopened = await importVaultFile(new Uint8Array(p12.data as Uint8Array).buffer, p12.filename, 'synthetic-password')
    expect(parseKeyMaterial(reopened.material).privateKey).toBe(key.privateKey)
    expect(parseKeyMaterial(reopened.material).certificates).toHaveLength(1)
    await expect(importVaultFile(new Uint8Array(p12.data as Uint8Array).buffer, p12.filename, 'incorrect')).rejects.toThrow('contraseña')
    await expect(exportVaultKey(key, 'pem', '')).rejects.toThrow('8 a 1024')
  }, 20_000)
  it('round trips RSA PEM and public JWK with signature interoperability', async () => {
    const key = parseKeyMaterial((await generateVaultKey('rsa', 2048)).material)
    const imported = await importVaultFile(new TextEncoder().encode(key.privateKey!).buffer, 'key.pem')
    expect(imported.bits).toBe(2048)
    expect(parseKeyMaterial(imported.material).publicKey).toBe(key.publicKey)
    const publicOnly = { ...key, privateKey: undefined }
    const exported = await exportVaultKey(publicOnly, 'jwk', '')
    const reopened = parseKeyMaterial((await importVaultFile(new TextEncoder().encode(exported.data as string).buffer, 'public.jwk')).material)
    expect(reopened.privateKey).toBeUndefined()
    expect(JSON.parse(await verifyJwt(reopened, await signJwt(key, '{"sub":"qa"}'))).payload.sub).toBe('qa')
  })
  it('preserves an encrypted private key and its complete PEM certificate collection regardless of order', async () => {
    const first = parseKeyMaterial((await generateVaultKey('ec', 'P-256')).material)
    const second = parseKeyMaterial((await generateVaultKey('ec', 'P-256')).material)
    const leaf = await createCertificateRequest(first, 'leaf.example.invalid', [], true)
    const other = await createCertificateRequest(second, 'other.example.invalid', [], true)
    const encrypted = await exportVaultKey(first, 'pem', 'synthetic-password')
    const bundle = [other, encrypted.data, leaf].join('\n')
    const reopened = parseKeyMaterial((await importVaultFile(new TextEncoder().encode(bundle).buffer, 'identity.pem', 'synthetic-password')).material)
    expect(reopened.privateKey).toBe(first.privateKey)
    expect(reopened.certificates).toEqual([leaf, other])
    await expect(importVaultFile(new TextEncoder().encode(bundle).buffer, 'identity.pem', 'incorrect')).rejects.toThrow('contraseña')
    await expect(importVaultFile(new TextEncoder().encode([first.privateKey, second.privateKey, leaf].join('\n')).buffer, 'two-keys.pem')).rejects.toThrow('varias claves')
    await expect(importVaultFile(new TextEncoder().encode('-----BEGIN RSA PRIVATE KEY-----\nAQID\n-----END RSA PRIVATE KEY-----\n' + leaf).buffer, 'legacy.pem')).rejects.toThrow('PKCS#8')
  }, 20_000)
  it('preserves every certificate in a certificate-only P12', async () => {
    const first = parseKeyMaterial((await generateVaultKey('ec', 'P-256')).material)
    const second = parseKeyMaterial((await generateVaultKey('ec', 'P-256')).material)
    const certificates = [await createCertificateRequest(first, 'first.example.invalid', [], true), await createCertificateRequest(second, 'second.example.invalid', [], true)]
    const safe = new pki.AuthenticatedSafe({ parsedValue: { safeContents: [{ privacyMode: 0, value: new pki.SafeContents({ safeBags: certificates.map(cert => new pki.SafeBag({ bagId: '1.2.840.113549.1.12.10.1.3', bagValue: new pki.CertBag({ parsedValue: pki.Certificate.fromBER(fromPem(cert, 'CERTIFICATE')) }) })) }) }] } })
    await safe.makeInternalValues({ safeContents: [{}] })
    const pfx = new pki.PFX({ parsedValue: { integrityMode: 0, authenticatedSafe: safe } })
    await pfx.makeInternalValues({ password: new TextEncoder().encode('synthetic-password').buffer, iterations: 1000, pbkdf2HashAlgorithm: 'SHA-256', hmacHashAlgorithm: 'SHA-256' })
    const reopened = parseKeyMaterial((await importVaultFile(pfx.toSchema().toBER(), 'certificates.p12', 'synthetic-password')).material)
    expect(reopened.certificates).toEqual(certificates)
    expect(reopened.privateKey).toBeUndefined()
    // An otherwise valid certificate collection must not hide an unsupported secret entry.
    safe.parsedValue.safeContents[0].value.safeBags.push(new pki.SafeBag({ bagId: '1.2.840.113549.1.12.10.1.5', bagValue: new pki.SecretBag({ secretTypeId: '1.2.3.4', secretValue: pki.PrivateKeyInfo.fromBER(fromPem(first.privateKey!, 'PRIVATE KEY')) }) }))
    await safe.makeInternalValues({ safeContents: [{}] })
    await pfx.makeInternalValues({ password: new TextEncoder().encode('synthetic-password').buffer, iterations: 1000, pbkdf2HashAlgorithm: 'SHA-256', hmacHashAlgorithm: 'SHA-256' })
    await expect(importVaultFile(pfx.toSchema().toBER(), 'unsupported.p12', 'synthetic-password')).rejects.toThrow('entradas no admitidas')
  })
  it('rejects excessive files, unsupported data and public-only signatures without changing a source', async () => {
    await expect(importVaultFile(new ArrayBuffer(1024 * 1024 + 1), 'oversized.p12')).rejects.toThrow('1 MiB')
    await expect(importVaultFile(new TextEncoder().encode('invalid').buffer, 'bad.pem')).rejects.toThrow('no compatible')
    expect(() => parseKeyMaterial('{"kind":"unknown"}')).toThrow('formato compatible')
    const key = parseKeyMaterial((await generateVaultKey('aes', 128)).material)
    await expect(signJwt(key, '{}')).rejects.toThrow('RSA o EC')
  })
})
