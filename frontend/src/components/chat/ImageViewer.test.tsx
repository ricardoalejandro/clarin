import { act, cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import ImageViewer from './ImageViewer'
import { StrictMode } from 'react'

beforeEach(() => {
  window.history.replaceState({ preserved: 'chat-route', __clarinMessageSelection: true }, '')
  vi.spyOn(window.history, 'back').mockImplementation(() => {})
  vi.stubGlobal('matchMedia', vi.fn(() => ({ matches: false, addEventListener: vi.fn(), removeEventListener: vi.fn() })))
})
afterEach(() => { cleanup(); vi.useRealTimers(); vi.restoreAllMocks(); vi.unstubAllGlobals() })

describe('image viewer', () => {
  it('shows loading, exposes a manual retry and resets the failure on a different source', () => {
    const { rerender } = render(<ImageViewer src="/first.jpg" isOpen onClose={vi.fn()} />)
    expect(screen.getByRole('status')).toHaveTextContent('Cargando imagen')
    fireEvent.error(screen.getByRole('img'))
    expect(screen.getByRole('alert')).toHaveTextContent('No se pudo cargar')
    expect(screen.queryByRole('img')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Reintentar imagen' }))
    fireEvent.load(screen.getByRole('img'))
    expect(screen.getByRole('button', { name: 'Descargar imagen' })).toBeEnabled()
    expect(screen.queryByRole('status')).not.toBeInTheDocument()
    rerender(<ImageViewer src="/second.jpg" isOpen onClose={vi.fn()} />)
    expect(screen.getByRole('img')).toHaveAttribute('src', '/second.jpg')
    expect(screen.getByRole('status')).toHaveTextContent('Cargando imagen')
  })
  it('bounds slow loading and never starts an automatic retry', () => {
    vi.useFakeTimers()
    render(<ImageViewer src="/slow.jpg" isOpen onClose={vi.fn()} />)
    act(() => vi.advanceTimersByTime(30_000))
    expect(screen.getByRole('alert')).toHaveTextContent('No se pudo cargar')
    act(() => vi.advanceTimersByTime(60_000))
    expect(screen.queryByRole('img')).not.toBeInTheDocument()
  })
  it('owns one Android Back entry while retaining other history state', async () => {
    const onClose = vi.fn()
    render(<ImageViewer src="/photo.jpg" isOpen onClose={onClose} />)
    await waitFor(() => expect(window.history.state).toMatchObject({ preserved: 'chat-route', __clarinMessageSelection: true, __clarinImageViewer: expect.any(String) }))
    const prior = { preserved: 'chat-route', __clarinMessageSelection: true }
    window.history.replaceState(prior, '')
    fireEvent.popState(window, { state: prior })
    expect(onClose).toHaveBeenCalledOnce()
    expect(window.history.back).not.toHaveBeenCalled()
  })
  it('closes explicitly without duplicating the Back close', async () => {
    const onClose = vi.fn()
    render(<ImageViewer src="/photo.jpg" isOpen onClose={onClose} />)
    await waitFor(() => expect(window.history.state.__clarinImageViewer).toEqual(expect.any(String)))
    fireEvent.click(screen.getByRole('button', { name: 'Cerrar visor' }))
    expect(window.history.back).toHaveBeenCalledOnce()
    fireEvent.popState(window, { state: {} })
    expect(onClose).toHaveBeenCalledOnce()
  })
  it('creates only one Back entry during StrictMode mount replay', async () => {
    const push = vi.spyOn(window.history, 'pushState')
    render(<StrictMode><ImageViewer src="/photo.jpg" isOpen onClose={vi.fn()} /></StrictMode>)
    await waitFor(() => expect(push).toHaveBeenCalledOnce())
    expect(window.history.back).not.toHaveBeenCalled()
  })
  it('traps keyboard focus, consumes Escape, and restores the invoking control', async () => {
    const trigger = document.createElement('button')
    document.body.appendChild(trigger)
    trigger.focus()
    const onClose = vi.fn()
    const { unmount } = render(<ImageViewer src="/photo.jpg" isOpen onClose={onClose} />)
    await waitFor(() => expect(screen.getByRole('dialog')).toHaveFocus())
    fireEvent.load(screen.getByRole('img'))
    const controls = within(screen.getByRole('dialog')).getAllByRole('button').filter(button => !button.hasAttribute('disabled'))
    controls.at(-1)!.focus()
    fireEvent.keyDown(window, { key: 'Tab' })
    expect(controls[0]).toHaveFocus()
    fireEvent.keyDown(window, { key: 'Escape' })
    expect(onClose).toHaveBeenCalledOnce()
    unmount()
    expect(trigger).toHaveFocus()
    trigger.remove()
  })
})

it('consumes native Ctrl-wheel and preserves normal wheel zoom only on the image surface', () => {
  const view = render(<ImageViewer src="/gesture.jpg" isOpen onClose={vi.fn()} />)
  const viewport = screen.getByTestId('image-viewer-surface')
  const ordinary = new WheelEvent('wheel', { bubbles: true, cancelable: true, deltaY: -100 })
  fireEvent(viewport, ordinary)
  expect(ordinary.defaultPrevented).toBe(true)
  expect(screen.getByTestId('image-viewer-scale')).toHaveTextContent('115%')
  const modified = new WheelEvent('wheel', { bubbles: true, cancelable: true, ctrlKey: true, deltaY: -100 })
  fireEvent(viewport, modified)
  expect(modified.defaultPrevented).toBe(true)
  expect(Number(viewport.dataset.imageScale)).toBeGreaterThan(1.15)
  const outside = new WheelEvent('wheel', { bubbles: true, cancelable: true, ctrlKey: true, deltaY: -100 })
  fireEvent(document.body, outside)
  expect(outside.defaultPrevented).toBe(false)
  view.rerender(<ImageViewer src="/next.jpg" isOpen onClose={vi.fn()} />)
  expect(screen.getByTestId('image-viewer-scale')).toHaveTextContent('100%')
  view.rerender(<ImageViewer src="/next.jpg" isOpen={false} onClose={vi.fn()} />)
  const retained = new WheelEvent('wheel', { bubbles: true, cancelable: true, ctrlKey: true, deltaY: -100 })
  fireEvent(viewport, retained)
  expect(retained.defaultPrevented).toBe(false)
})

it('keeps mobile two-finger zoom and rotation inside the existing chat window', () => {
  class MobilePointerEvent extends MouseEvent {
    pointerId: number
    pointerType: string
    constructor(type: string, values: PointerEventInit = {}) { super(type, values); this.pointerId = values.pointerId ?? 1; this.pointerType = 'touch' }
  }
  vi.stubGlobal('PointerEvent', MobilePointerEvent)
  vi.stubGlobal('innerWidth', 375)
  vi.stubGlobal('matchMedia', vi.fn(() => ({ matches: true, addEventListener: vi.fn(), removeEventListener: vi.fn() })))
  render(<ImageViewer src="/mobile.jpg" isOpen onClose={vi.fn()} />)
  const dialog = screen.getByRole('dialog')
  const viewport = screen.getByTestId('image-viewer-surface')
  const image = screen.getByRole('img')
  Object.defineProperties(viewport, { clientWidth: { configurable: true, value: 300 }, clientHeight: { configurable: true, value: 300 } })
  viewport.getBoundingClientRect = () => ({ left: 0, top: 0, width: 300, height: 300, right: 300, bottom: 300, x: 0, y: 0, toJSON() {} })
  Object.defineProperties(image, { offsetWidth: { configurable: true, value: 300 }, offsetHeight: { configurable: true, value: 200 } })
  fireEvent.load(image)
  const input = (type: string, id: number, x: number) => fireEvent(viewport, new MobilePointerEvent(type, { bubbles: true, cancelable: true, pointerId: id, clientX: x, clientY: 150 }))
  input('pointerdown', 1, 100); input('pointerdown', 2, 200); input('pointermove', 2, 300)
  expect(viewport).toHaveAttribute('data-image-scale', '2')
  expect(screen.getByRole('dialog')).toBe(dialog)
  input('pointerup', 2, 300); input('pointerup', 1, 100)
  fireEvent.click(screen.getByRole('button', { name: 'Rotar imagen' }))
  expect(image.style.transform).toContain('rotate(90deg)')
  expect(viewport).toHaveAttribute('data-image-scale', '2')
  fireEvent.keyDown(window, { key: '0' })
  expect(image.style.transform).toContain('rotate(0deg)')
  expect(viewport).toHaveAttribute('data-image-scale', '1')
})

it('keeps a replaced image session loading despite events from its detached predecessor', () => {
  const view = render(<ImageViewer src="/old-session.jpg" isOpen onClose={vi.fn()} />)
  const oldImage = screen.getByRole('img')
  view.rerender(<ImageViewer src="/new-session.jpg" isOpen onClose={vi.fn()} />)
  fireEvent.load(oldImage)
  fireEvent.error(oldImage)
  expect(screen.getByRole('status')).toHaveTextContent('Cargando imagen')
  expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  expect(screen.getByRole('button', { name: 'Descargar imagen' })).toBeDisabled()
  fireEvent.load(screen.getByRole('img'))
  expect(screen.getByRole('button', { name: 'Descargar imagen' })).toBeEnabled()
})
