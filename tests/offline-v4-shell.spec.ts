test('offline mode survives reconnection, reload and another tab without resuming an older online cookie', async ({ page, context }) => {
  await prepareWorker(page)
  await context.addCookies([{ name:'qa_navigation',value:'preserve',url:origin }])
  expect(await workerMessage(page, {type:'CLARIN_OFFLINE_V4_SET_MODE',mode:'offline'})).toMatchObject({ok:true})
  cookieSeen = false
  // Origin is healthy throughout this test. The stale cookie must not select
  // the actor merely because the browser reloads or opens an unsupported URL.
  for (const path of ['/dashboard/tasks','/dashboard/chats','/login']) {
    await page.goto(origin+path)
    await expect(page.locator('#clarin-offline-root')).toBeVisible()
    await expect(page.locator('body')).not.toContainText(privateSentinel)
  }
  await page.reload()
  await expect(page.locator('#clarin-offline-root')).toBeVisible()
  const otherTab = await context.newPage()
  await otherTab.goto(origin+'/dashboard')
  await expect(otherTab.locator('#clarin-offline-root')).toBeVisible()
  await otherTab.close()
  expect(cookieSeen).toBe(false)
  expect(await workerMessage(page, {type:'CLARIN_OFFLINE_V4_SET_MODE',mode:'online'})).toMatchObject({ok:false})
  expect(await workerMessage(page, {type:'CLARIN_OFFLINE_V4_BEGIN_ONLINE_REAUTH'})).toMatchObject({ok:true})
  await page.goto(origin+'/login?offline_reauth=1')
  await expect(page.getByRole('heading',{name:'Online fixture'})).toBeVisible()
  await page.goto(origin+'/dashboard/tasks')
  await expect(page.locator('#clarin-offline-root')).toBeVisible()
  // The real login handler separately enforces password/Turnstile and exact
  // actor/account before its UI is permitted to send this completion message.
  expect(await workerMessage(page, {type:'CLARIN_OFFLINE_V4_SET_MODE',mode:'online'})).toMatchObject({ok:true})
  await page.goto(origin+'/dashboard/tasks')
  await expect(page.getByRole('heading',{name:'Online fixture'})).toBeVisible()
})

test('an update with a corrupt asset cannot replace the last verified offline shell', async ({ page, context }) => {
  await prepareWorker(page)
  const previous = await page.evaluate(async () => {
    const response = await (await caches.open('clarin-offline-v4-meta-v1')).match('/offline-v4/.runtime-meta.json')
    return (await response!.json()).shell_generations
  })
  corruptManifest = true
  const update = await page.evaluate(() => new Promise(resolve => {
    const channel = new MessageChannel()
    channel.port1.onmessage = event => { channel.port1.close(); resolve(event.data) }
    navigator.serviceWorker.controller!.postMessage({type:'CLARIN_OFFLINE_V4_SET_ENABLED', enabled:true},[channel.port2])
  }))
  expect(update).toMatchObject({ok:false,error:'offline_shell_unavailable'})
  const after = await page.evaluate(async () => {
    const response = await (await caches.open('clarin-offline-v4-meta-v1')).match('/offline-v4/.runtime-meta.json')
    return await response!.json()
  })
  expect(after.enabled).toBe(true)
  expect(after.shell_generations).toEqual(previous)
  originUnavailable = true
  await context.setOffline(true)
  await page.goto(origin+'/dashboard/tasks')
  await expect(page.locator('#clarin-offline-root')).toBeVisible()
})

