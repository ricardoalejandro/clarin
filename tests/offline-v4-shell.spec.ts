test('the public shell survives a complete browser-process close and offline reopen', async ({ playwright }, testInfo) => {
  const profile = await mkdtemp(resolve(tmpdir(), 'clarin-offline-v4-shell-'))
  const launchOptions = testInfo.project.use.launchOptions || {}
  let persistent = await playwright.chromium.launchPersistentContext(profile, { ...launchOptions, headless: true })
  try {
    await prepareWorker(persistent.pages()[0] || await persistent.newPage())
    await persistent.close()
    originUnavailable = true
    persistent = await playwright.chromium.launchPersistentContext(profile, { ...launchOptions, headless: true })
    const reopened = persistent.pages()[0] || await persistent.newPage()
    await reopened.goto(origin + '/dashboard/tasks')
    await expect(reopened.locator('#clarin-offline-root')).toBeVisible()
    await expect(reopened.locator('body')).not.toContainText(privateSentinel)
    await expect(reopened.locator('[data-mode="offline"]')).toHaveCount(0)
  } finally {
    originUnavailable = false
    await persistent.close()
    // This exact temporary, synthetic profile is owned by this test.
    await rm(profile, { recursive: true, force: true })
  }
})

